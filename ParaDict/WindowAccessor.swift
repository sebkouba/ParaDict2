import SwiftUI
import AppKit

/// A SwiftUI view that captures the NSWindow when it becomes available.
/// Used to register windows with WindowManager for proper lifecycle management.
struct WindowAccessor: NSViewRepresentable {
    let callback: (NSWindow) -> Void

    func makeNSView(context: Context) -> NSView {
        let view = NSView()
        DispatchQueue.main.async {
            if let window = view.window {
                callback(window)
            }
        }
        return view
    }

    func updateNSView(_ nsView: NSView, context: Context) {}
}
